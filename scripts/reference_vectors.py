"""Generate independent encode/decode vectors with galois 0.4.11 (MIT).

Run with PYTHONPATH=D:/Codex/tools/bch-reference. The generated tests do not
require Python, galois or native compilation to run.
"""
from pathlib import Path
import json, random
import galois

root = Path(__file__).resolve().parents[1]
rng = random.Random(20261030)
polys = [0,0,0x7,0xb,0x13,0x25,0x43,0x83,0x11d,0x211,0x409]
vectors = []
for m in range(2, 11):
    for t in range(1, min(3, ((1 << m)-2)//2)+1):
        field = galois.GF(2**m, irreducible_poly=polys[m])
        code = galois.BCH(2**m-1, d=2*t+1, extension_field=field)
        for size in sorted(set([1, min(9,code.k), code.k])):
            msg = galois.GF2([rng.randrange(2) for _ in range(size)])
            word = code.encode(msg)
            positions = sorted(rng.sample(range(len(word)), t))
            corrupt = word.copy()
            corrupt[positions] ^= 1
            decoded, errors = code.decode(corrupt, errors=True)
            assert decoded.tolist() == msg.tolist() and int(errors) == t
            text = lambda values: ''.join(map(str, values.tolist()))
            vectors.append(dict(m=m,t=t,primitive=polys[m],message=text(msg),encoded=text(word),corrupt=text(corrupt),positions=positions))
out = root/'examples'; out.mkdir(exist_ok=True)
(out/'galois-vectors.json').write_text(json.dumps(dict(reference='galois',version=galois.__version__,seed=20261030,vectors=vectors),indent=2),encoding='utf-8')
lines = ['// Generated by scripts/reference_vectors.py using galois, not this implementation.',
 'fn vb(s : String) -> Array[Int] { let a : Array[Int] = []; for c in s { a.push(if c == \'1\' { 1 } else { 0 }) }; a }',
 'test "independent galois reference encoding decoding and positions" {']
for v in vectors:
    lines.extend(['  {',f'    let c = Bch::new({v["m"]},{v["t"]},primitive={v["primitive"]})',
      f'    let msg = vb("{v["message"]}")',f'    assert_eq(c.encode(msg),vb("{v["encoded"]}"))',
      f'    let fixed = c.decode(vb("{v["corrupt"]}"))', '    assert_eq(fixed.message,msg)',
      f'    assert_eq(fixed.corrected_positions,{v["positions"]})','  }'])
lines.append('}')
(root/'reference_test.mbt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'galois {galois.__version__}: {len(vectors)} independently generated encoding and decoding vectors')
